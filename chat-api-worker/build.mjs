import { readFileSync, writeFileSync } from 'node:fs';
const worker = readFileSync(new URL('./worker.mjs', import.meta.url), 'utf8')
  .replace("import { SYSTEM_PROMPT } from './prompt.mjs';", '').replaceAll('export function ', 'function ');
const prompt = readFileSync(new URL('./prompt.mjs', import.meta.url), 'utf8').replace('export const SYSTEM_PROMPT', 'const SYSTEM_PROMPT');
writeFileSync(new URL('./deploy.js', import.meta.url), '// Generated by node build.mjs; single-file Cloudflare dashboard deployment.\n' + prompt + worker);
